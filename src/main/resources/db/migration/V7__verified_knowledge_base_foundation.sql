-- Add the domain foundation for source-backed reference data and moderation.
-- This migration intentionally adds no medical claims or synthetic records.

ALTER TABLE plants
    ADD COLUMN name_ru VARCHAR(250);
ALTER TABLE plants ADD COLUMN name_kk VARCHAR(250);
ALTER TABLE plants ADD COLUMN synonyms TEXT;
ALTER TABLE plants ADD COLUMN distribution_regions TEXT;
ALTER TABLE plants ADD COLUMN used_parts TEXT;
ALTER TABLE plants ADD COLUMN review_status VARCHAR(30) NOT NULL DEFAULT 'UNVERIFIED';

ALTER TABLE plants
    ADD CONSTRAINT ck_plants_review_status
        CHECK (review_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED'));

CREATE TABLE user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    display_name VARCHAR(200) NOT NULL,
    password_hash VARCHAR(200) NOT NULL,
    role VARCHAR(30) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_accounts_role CHECK (role IN ('USER', 'EXPERT', 'ADMIN'))
);

CREATE TABLE plant_names (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT NOT NULL REFERENCES plants (id) ON DELETE CASCADE,
    language_code VARCHAR(10) NOT NULL,
    name VARCHAR(250) NOT NULL,
    name_type VARCHAR(30) NOT NULL DEFAULT 'COMMON',
    source_id BIGINT REFERENCES sources (id) ON DELETE SET NULL,
    review_status VARCHAR(30) NOT NULL DEFAULT 'UNVERIFIED',
    CONSTRAINT ck_plant_names_language CHECK (language_code IN ('ru', 'kk', 'la', 'en')),
    CONSTRAINT ck_plant_names_type CHECK (name_type IN ('COMMON', 'SYNONYM', 'SCIENTIFIC')),
    CONSTRAINT ck_plant_names_review_status CHECK (review_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT uq_plant_names_value UNIQUE (plant_id, language_code, name)
);
CREATE INDEX ix_plant_names_search ON plant_names (language_code, name);

CREATE TABLE preparations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(500) NOT NULL,
    dosage_form VARCHAR(200),
    manufacturer VARCHAR(500),
    registration_number VARCHAR(250) UNIQUE,
    registration_country VARCHAR(100),
    description TEXT,
    source_id BIGINT NOT NULL REFERENCES sources (id),
    review_status VARCHAR(30) NOT NULL DEFAULT 'UNVERIFIED',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_preparations_review_status CHECK (review_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED'))
);
CREATE INDEX ix_preparations_name ON preparations (name);

CREATE TABLE preparation_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preparation_id BIGINT NOT NULL REFERENCES preparations (id) ON DELETE CASCADE,
    plant_id BIGINT REFERENCES plants (id),
    compound_id BIGINT REFERENCES compounds (id),
    ingredient_name VARCHAR(500),
    quantity VARCHAR(250),
    source_id BIGINT NOT NULL REFERENCES sources (id),
    review_status VARCHAR(30) NOT NULL DEFAULT 'UNVERIFIED',
    CONSTRAINT ck_preparation_ingredient_subject CHECK (
        (plant_id IS NOT NULL AND compound_id IS NULL)
        OR (plant_id IS NULL AND compound_id IS NOT NULL)
    ),
    CONSTRAINT ck_preparation_ingredient_review CHECK (review_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED'))
);
CREATE INDEX ix_preparation_ingredients_preparation ON preparation_ingredients (preparation_id);
CREATE INDEX ix_preparation_ingredients_plant ON preparation_ingredients (plant_id);
CREATE INDEX ix_preparation_ingredients_compound ON preparation_ingredients (compound_id);

CREATE TABLE knowledge_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT REFERENCES plants (id) ON DELETE CASCADE,
    preparation_id BIGINT REFERENCES preparations (id) ON DELETE CASCADE,
    claim_type VARCHAR(40) NOT NULL,
    title VARCHAR(500) NOT NULL,
    claim_text TEXT NOT NULL,
    interaction_partner VARCHAR(500),
    source_id BIGINT NOT NULL REFERENCES sources (id),
    source_locator VARCHAR(500),
    review_status VARCHAR(30) NOT NULL DEFAULT 'UNVERIFIED',
    created_by BIGINT REFERENCES user_accounts (id) ON DELETE SET NULL,
    reviewed_by BIGINT REFERENCES user_accounts (id) ON DELETE SET NULL,
    review_note TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_knowledge_claim_subject CHECK (
        (plant_id IS NOT NULL AND preparation_id IS NULL)
        OR (plant_id IS NULL AND preparation_id IS NOT NULL)
    ),
    CONSTRAINT ck_knowledge_claim_type CHECK (claim_type IN ('INDICATION', 'CONTRAINDICATION', 'INTERACTION')),
    CONSTRAINT ck_knowledge_claim_review CHECK (review_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT ck_knowledge_claim_interaction CHECK (claim_type <> 'INTERACTION' OR interaction_partner IS NOT NULL)
);
CREATE INDEX ix_knowledge_claims_plant_status ON knowledge_claims (plant_id, review_status);
CREATE INDEX ix_knowledge_claims_preparation_status ON knowledge_claims (preparation_id, review_status);
CREATE INDEX ix_knowledge_claims_type_status ON knowledge_claims (claim_type, review_status);

CREATE TABLE knowledge_claim_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL REFERENCES knowledge_claims (id) ON DELETE CASCADE,
    reviewer_id BIGINT NOT NULL REFERENCES user_accounts (id),
    previous_status VARCHAR(30) NOT NULL,
    new_status VARCHAR(30) NOT NULL,
    review_note TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_claim_review_previous CHECK (previous_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT ck_claim_review_new CHECK (new_status IN ('PENDING', 'VERIFIED', 'REJECTED'))
);
CREATE INDEX ix_knowledge_claim_reviews_claim ON knowledge_claim_reviews (claim_id, created_at);

CREATE TABLE user_favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_accounts (id) ON DELETE CASCADE,
    plant_id BIGINT REFERENCES plants (id) ON DELETE CASCADE,
    compound_id BIGINT REFERENCES compounds (id) ON DELETE CASCADE,
    preparation_id BIGINT REFERENCES preparations (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_favorite_one_subject CHECK (
        (CASE WHEN plant_id IS NULL THEN 0 ELSE 1 END)
        + (CASE WHEN compound_id IS NULL THEN 0 ELSE 1 END)
        + (CASE WHEN preparation_id IS NULL THEN 0 ELSE 1 END) = 1
    ),
    CONSTRAINT uq_user_favorite_plant UNIQUE (user_id, plant_id),
    CONSTRAINT uq_user_favorite_compound UNIQUE (user_id, compound_id),
    CONSTRAINT uq_user_favorite_preparation UNIQUE (user_id, preparation_id)
);

CREATE TABLE assistant_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_accounts (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_assistant_conversations_user ON assistant_conversations (user_id, updated_at);

CREATE TABLE assistant_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES assistant_conversations (id) ON DELETE CASCADE,
    message_role VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    response_status VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_assistant_message_role CHECK (message_role IN ('USER', 'ASSISTANT'))
);
CREATE INDEX ix_assistant_messages_conversation ON assistant_messages (conversation_id, created_at);

CREATE TABLE assistant_message_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES assistant_messages (id) ON DELETE CASCADE,
    source_id BIGINT NOT NULL REFERENCES sources (id),
    source_locator VARCHAR(500),
    excerpt TEXT,
    CONSTRAINT uq_assistant_message_source UNIQUE (message_id, source_id, source_locator)
);
