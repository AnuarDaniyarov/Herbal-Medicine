ALTER TABLE predictions
    ADD COLUMN created_by BIGINT REFERENCES user_accounts (id) ON DELETE SET NULL;

CREATE INDEX ix_predictions_created_by_created_at
    ON predictions (created_by, created_at);

CREATE TABLE knowledge_claim_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL REFERENCES knowledge_claims (id) ON DELETE CASCADE,
    editor_id BIGINT NOT NULL REFERENCES user_accounts (id),
    before_title VARCHAR(500),
    after_title VARCHAR(500),
    before_claim_text TEXT,
    after_claim_text TEXT,
    before_interaction_partner VARCHAR(500),
    after_interaction_partner VARCHAR(500),
    before_source_locator VARCHAR(500),
    after_source_locator VARCHAR(500),
    edited_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_knowledge_claim_revisions_claim_id
    ON knowledge_claim_revisions (claim_id, edited_at);
