CREATE TABLE targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    normalized_identifier VARCHAR(200) NOT NULL UNIQUE,
    name VARCHAR(250) NOT NULL,
    organism VARCHAR(250),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE plant_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT NOT NULL REFERENCES plants (id) ON DELETE CASCADE,
    plant_part VARCHAR(250),
    origin VARCHAR(500),
    batch_identifier VARCHAR(250),
    collected_on DATE,
    metadata TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_plant_samples_plant ON plant_samples (plant_id);

CREATE TABLE extracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id BIGINT NOT NULL REFERENCES plant_samples (id) ON DELETE CASCADE,
    extraction_method VARCHAR(250),
    solvent VARCHAR(250),
    conditions TEXT,
    batch_identifier VARCHAR(250),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_extracts_sample ON extracts (sample_id);

ALTER TABLE plant_compound_relationships
    ADD COLUMN sample_id BIGINT REFERENCES plant_samples (id) ON DELETE SET NULL;
ALTER TABLE plant_compound_relationships
    ADD COLUMN extract_id BIGINT REFERENCES extracts (id) ON DELETE SET NULL;
CREATE INDEX ix_plant_compound_relationships_sample ON plant_compound_relationships (sample_id);
CREATE INDEX ix_plant_compound_relationships_extract ON plant_compound_relationships (extract_id);

ALTER TABLE assays
    ADD COLUMN target_id BIGINT REFERENCES targets (id) ON DELETE SET NULL;
CREATE INDEX ix_assays_target ON assays (target_id);

ALTER TABLE activity_measurements
    ALTER COLUMN compound_id DROP NOT NULL;
ALTER TABLE activity_measurements
    ADD COLUMN extract_id BIGINT REFERENCES extracts (id) ON DELETE CASCADE;
ALTER TABLE activity_measurements
    ADD CONSTRAINT ck_activity_measurements_one_candidate CHECK (
        (compound_id IS NOT NULL AND extract_id IS NULL)
        OR (compound_id IS NULL AND extract_id IS NOT NULL)
    );
CREATE INDEX ix_activity_measurements_extract ON activity_measurements (extract_id);

ALTER TABLE sources ADD COLUMN license_note TEXT;
ALTER TABLE predictions ADD COLUMN uncertainty DECIMAL(18, 8);
